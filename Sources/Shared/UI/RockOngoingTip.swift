import TipKit

/// 红石条「进行中」的呼吸光环，第一次出现时解释一次。
///
/// 为什么值得给这条动效配一个 Tip：
/// 动效本身是"无声的"——用户看到图标在脉冲，不知道是因为场次进行中，
/// 还是因为网络在加载、或者单纯是装饰。一句解释能把这个歧义消掉，
/// 之后这个动效就变成可读的状态指示，而不是背景噪音。
///
/// 为什么用 TipKit 而不是自己弹一次提示：
/// TipKit 自己处理"只显示一次""用户看过就不再打扰""跨设备同步已读"，
/// 自己实现要么重复造轮子，要么写成永远只弹一次的 `@AppStorage` 标志——
/// 那样升级、重装、换设备都会再弹一次，用户会烦。
struct RockOngoingTip: Tip {
    var title: Text {
        Text("场次进行中")
    }

    var message: Text? {
        Text("左侧图标的脉冲和外圈呼吸表示这一场正在打，不是加载中。")
    }

    var image: Image? {
        Image(systemName: "moon.stars")
    }
}
